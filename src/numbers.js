// 예시 데이터입니다. 실제 재고가 아닙니다.
export const SAMPLE = [
  ['+1 (415) 555-0123', 'US', '415', '샌프란시스코'], ['+1 (415) 555-0148', 'US', '415', '샌프란시스코'],
  ['+1 (415) 555-0171', 'US', '415', '샌프란시스코'], ['+1 (212) 555-0116', 'US', '212', '뉴욕'],
  ['+1 (212) 555-0192', 'US', '212', '뉴욕'], ['+1 (310) 555-0134', 'US', '310', '로스앤젤레스'],
  ['+1 (310) 555-0187', 'US', '310', '로스앤젤레스'], ['+1 (416) 555-0129', 'CA', '416', '토론토'],
  ['+1 (416) 555-0163', 'CA', '416', '토론토'], ['+1 (604) 555-0155', 'CA', '604', '밴쿠버']
].map(([number, country, area, city]) => ({ number, country, area, city }));

export function search(country, area) {
  const c = (country || 'US').toUpperCase();
  const a = (area || '').replace(/\D/g, '').slice(0, 3);
  return SAMPLE.filter(n => n.country === c && (!a || n.area === a));
}
